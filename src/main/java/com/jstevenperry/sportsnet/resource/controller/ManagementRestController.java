package com.jstevenperry.sportsnet.resource.controller;

import com.jstevenperry.sportsnet.framework.dto.ManagementEventDto;
import com.jstevenperry.sportsnet.framework.dto.ManagementEventSummaryDto;
import com.jstevenperry.sportsnet.framework.model.ManagementEvent;
import com.jstevenperry.sportsnet.framework.model.ManagementEventSummary;
import com.jstevenperry.sportsnet.framework.model.ManagementEventType;
import com.jstevenperry.sportsnet.resource.service.ManagementService;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;
import org.springframework.web.servlet.support.ServletUriComponentsBuilder;

import java.net.URI;
import java.util.List;
import java.util.UUID;
import java.util.stream.Collectors;

@RestController
@RequestMapping("/management")
public class ManagementRestController {

    private static final Logger log = LoggerFactory.getLogger(ManagementRestController.class);

    private final ManagementService managementService;

    public ManagementRestController(final ManagementService managementService) {
        this.managementService = managementService;
    }

    /**
     * Register a single event using the information contained in the DTO from the request body
     * and return a decorated ManagementEvent DTO in the response body, having at least the
     * eventId generated by the service (and possibly others at its discretion). If the correlationId
     * is null the service will use the eventId as the correlationId so the sender does not have
     * to create one a priori and can associate events with one another after-the-fact.
     *
     * @param managementEventDto Contains information about the event to be registered. At a minimum
     *                           must contain the event type and host name.
     * @return ResponseEntity containing the decorated ManagementEventDto
     */
    @PostMapping("/events")
    public ResponseEntity<ManagementEventDto> createEvent(@RequestBody final ManagementEventDto managementEventDto) {
        long startTime = System.currentTimeMillis();

        final ManagementEvent managementEvent = ManagementEvent.fromDto(managementEventDto);

        final ManagementEvent registeredEvent = managementService.createEvent(managementEvent);
        final ManagementEventDto dto = registeredEvent.toDto();

        URI location = ServletUriComponentsBuilder
                .fromCurrentRequest()
                .path("/{eventId}")
                .buildAndExpand(dto.getEventId())
                .toUri();
        log.debug("createEvent(): Created event {} at URI {} in {}ms", dto.getManagementEventType(), location, System.currentTimeMillis() - startTime);
        return ResponseEntity.created(location)
                .body(dto);
    }

    /**
     * Fetch and return all registered events. This may be as useful and poorly performant as it sounds.
     *
     * @return ResponseEntity containing all registered ManagementEventDto
     */
    @GetMapping("/events")
    public ResponseEntity<List<ManagementEventDto>> fetchAllEvents() {
        long startTime = System.currentTimeMillis();

        final List<ManagementEvent> registeredEvents = managementService.fetchAllEvents();
        final List<ManagementEventDto> dtos = registeredEvents.stream()
                .map(ManagementEvent::toDto)
                .collect(Collectors.toList());

        log.debug("fetchAllEvents(): Found {} registered events in {}ms", dtos.size(), System.currentTimeMillis() - startTime);
        return ResponseEntity.ok(dtos);
    }

    /**
     * Fetch by ID and return the DTO representation of the specified event.
     *
     * @param eventId The event ID of the event to fetch. If the event cannot be found a NotFoundException
     *                will be thrown.
     * @return ResponseEntity containing the ManagementEventDto if found, or a NotFoundException is thrown
     * if the event could not be located.
     */
    @GetMapping("/events/{eventId}")
    public ResponseEntity<ManagementEventDto> fetchEventById(@PathVariable(name = "eventId") final UUID eventId) {
        long startTime = System.currentTimeMillis();

        final ManagementEvent registeredEvent = managementService.fetchEventById(eventId);
        final ManagementEventDto dto = registeredEvent.toDto();

        log.debug("fetchEventById(): Found registered event {} in {}ms", dto.getEventId(), System.currentTimeMillis() - startTime);
        return ResponseEntity.ok(dto);
    }

    /**
     * Fetch by various search parameters and return all matching correlated events.
     * At least one of the documented criteria must be supplied or a BadRequestException will be
     * thrown. If you need to fetch all events, this is not the endpoint you're looking for.
     *
     * @param correlationId The correlation ID to search for
     * @param sport         The sport to search for
     * @param mostRecentN   The most recent N events matching the other criteria
     * @return ResponseEntity containing a list of DTO representations of matching events, or an empty
     * list if none could be found matching the specified criteria.
     */
    @GetMapping("/searchEvents")
    public ResponseEntity<List<ManagementEventDto>> searchEvents(
            @RequestParam(required = false) final UUID correlationId,
            @RequestParam(required = false) final String sport,
            @RequestParam(required = false) final List<ManagementEventType> managementEventType,
            @RequestParam(required = false) final Integer mostRecentN) {
        long startTime = System.currentTimeMillis();

        final List<ManagementEvent> registeredCorrelatedEvents = managementService.fetchCorrelatedEvents(
                correlationId, sport, managementEventType, mostRecentN
        );
        final List<ManagementEventDto> dtos = registeredCorrelatedEvents.stream()
                .map(ManagementEvent::toDto)
                .collect(Collectors.toList());

        log.debug("searchEvents(): Found {} registered and correlated events in {}ms", dtos.size(), System.currentTimeMillis() - startTime);
        return ResponseEntity.ok(dtos);
    }

    @GetMapping("/stats")
    public ResponseEntity<List<ManagementEventSummaryDto>> getStats(
            @RequestParam(required = false) final UUID correlationId,
            @RequestParam(required = false) final String sport,
            @RequestParam(required = false) final List<ManagementEventType> managementEventType,
            @RequestParam(required = false) final Integer mostRecentN) {
        long startTime = System.currentTimeMillis();

        final List<ManagementEvent> registeredCorrelatedEvents = managementService.fetchCorrelatedEvents(
                correlationId, sport, managementEventType, mostRecentN
        );

        final List<ManagementEventSummary> managementEventSummaries = managementService.computeStats(registeredCorrelatedEvents);

        final List<ManagementEventSummaryDto> dtos = managementEventSummaries.stream()
                .map(ManagementEventSummary::toDto)
                .collect(Collectors.toList());

        log.debug("getStats(): Found {} registered and correlated events in {}ms", dtos.size(), System.currentTimeMillis() - startTime);
        return ResponseEntity.ok(dtos);

    }
}
